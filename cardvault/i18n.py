def _windows_ui_language():
    """Windows UI language (e.g. 'ro' for a Romanian Windows)."""
    try:
        import ctypes
        lang_id = ctypes.windll.kernel32.GetUserDefaultUILanguage()
        name = locale.windows_locale.get(lang_id)  # ex. 'ro_RO'
        if name:
            return name.split("_")[0].lower()
    except Exception:
        pass
    return None


def detect_system_language() -> str:
    candidates = []
    if sys.platform == "win32":
        candidates.append(_windows_ui_language())
    try:
        from PySide6.QtCore import QLocale
        candidates.append(QLocale.system().name().split("_")[0].lower())
    except Exception:
        pass
    for var in ("LANGUAGE", "LC_ALL", "LC_MESSAGES", "LANG"):
        val = os.environ.get(var)
        if val:
            candidates.append(val.split(":")[0].split("_")[0].split(".")[0].lower())
    try:
        loc = locale.getlocale()[0]
        if loc:
            candidates.append(loc.split("_")[0].lower())
    except Exception:
        pass
    for code in candidates:
        if code in T:
            return code
    return DEFAULT_LANG


class Translator:
    def __init__(self, lang: str):
        self.lang = lang if lang in T else DEFAULT_LANG

    def __call__(self, key: str, **kw) -> str:
        text = T[self.lang].get(key) or T[DEFAULT_LANG].get(key, key)
        return text.format(**kw) if kw else text
